_LANGS = {"zh": _ZH, "en": _EN}


def lang() -> str:
    value = str(appconfig.get("language", "zh") or "zh")
    return value if value in _LANGS else "zh"


def tr(key: str, **kwargs) -> str:
    table = _LANGS[lang()]
    text = table.get(key) or _ZH.get(key) or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except Exception:
            pass
    return text
